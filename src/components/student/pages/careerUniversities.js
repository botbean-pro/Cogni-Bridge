const lookup = (ids) => ids.map((id) => ({ id, ...institutions[id] }));

// { places: [...], portals: [...] } for one career.
export const institutionsFor = (careerId) => {
  const all = lookup(careerInstitutions[careerId] || []);
  return { places: all.filter((item) => !item.body), portals: all.filter((item) => item.body) };
};

// The places that show up for most careers in a stream, so students can see where a whole stream leads.
export const streamPlaces = (streamId, limit = 8) => {
  const stream = careerStreams.find((item) => item.id === streamId);
  const counts = new Map();
  (stream?.careers || []).forEach((career) => institutionsFor(career.id).places.forEach((place) => counts.set(place.id, (counts.get(place.id) || 0) + 1)));
  return [...counts.entries()].sort((a, b) => b[1] - a[1]).slice(0, limit).map(([id]) => ({ id, ...institutions[id] }));
};
